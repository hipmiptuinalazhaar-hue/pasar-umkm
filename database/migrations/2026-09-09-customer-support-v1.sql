-- Additive launch-hardening migration:
-- 1. Private user <-> platform support tickets.
-- 2. Support messages, evidence images, and internal admin notes.
-- 3. Explicit admin RBAC capabilities for support agents.
-- 4. Read/unread timestamps and operational indexes.
--
-- No existing marketplace/chat/order table is mutated.
